//! The currencies the system handles.
//!
//! One shared type across the crate: the portfolio calculator treats it as the
//! set it can report in and convert between, and the ledger uses it as the
//! commodity label on a posting. The variants are the ISO 4217 currency codes —
//! the same set a normal accounting app offers — so a currency the ledger meets
//! parses into the type instead of reaching a posting as an unchecked string.
//!
//! Deliberately excluded are the ISO 4217 codes that are not spendable
//! currency: precious metals (XAU, XAG, XPT, XPD), the SDR and other units of
//! account, the testing code XTS and the no-currency code XXX. Those are
//! commodities or placeholders, valued as held positions rather than
//! denominated in — the same reason crypto is modelled as a security, not a
//! currency.

